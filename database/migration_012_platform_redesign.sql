-- Ardhi Way platform redesign: roles, KYC, locations, listing workflow,
-- messaging, buyer interests, and expert matching.
SET NAMES utf8mb4;

ALTER TABLE users
  MODIFY COLUMN role ENUM('buyer','seller','agent','expert','admin') NOT NULL DEFAULT 'buyer',
  ADD COLUMN verification_status ENUM('not_required','pending','under_review','verified','rejected') NOT NULL DEFAULT 'pending',
  ADD COLUMN verification_notes TEXT NULL,
  ADD COLUMN verified_at TIMESTAMP NULL,
  ADD COLUMN verified_by_user_id INT UNSIGNED NULL,
  ADD COLUMN nida_number VARCHAR(40) NULL,
  ADD COLUMN address_text VARCHAR(255) NULL,
  ADD COLUMN passport_photo_path VARCHAR(255) NULL,
  ADD COLUMN account_type ENUM('individual','company') NOT NULL DEFAULT 'individual',
  ADD COLUMN company_name VARCHAR(190) NULL,
  ADD COLUMN brela_number VARCHAR(80) NULL,
  ADD COLUMN tin_number VARCHAR(80) NULL,
  ADD COLUMN expert_type ENUM('surveyor','valuer','town_planner','advocate') NULL,
  ADD COLUMN region_code VARCHAR(10) NULL,
  ADD COLUMN district_code VARCHAR(10) NULL,
  ADD COLUMN ward_code VARCHAR(20) NULL,
  ADD COLUMN is_super_admin TINYINT(1) NOT NULL DEFAULT 0,
  ADD KEY idx_users_role_verification (role, verification_status),
  ADD KEY idx_users_location (region_code, district_code, ward_code);

UPDATE users SET verification_status = 'not_required' WHERE role = 'buyer';
UPDATE users SET verification_status = 'verified', verified_at = COALESCE(verified_at, NOW()) WHERE role = 'admin';
UPDATE users SET is_super_admin = 1 WHERE role = 'admin' AND email = 'admin@ardhiguide.local';

CREATE TABLE IF NOT EXISTS locations_regions (
  code VARCHAR(10) NOT NULL,
  name VARCHAR(120) NOT NULL,
  PRIMARY KEY (code),
  UNIQUE KEY uniq_locations_region_name (name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS locations_districts (
  region_code VARCHAR(10) NOT NULL,
  code VARCHAR(10) NOT NULL,
  name VARCHAR(120) NOT NULL,
  PRIMARY KEY (region_code, code),
  KEY idx_locations_district_name (name),
  CONSTRAINT fk_locations_district_region FOREIGN KEY (region_code) REFERENCES locations_regions(code) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS locations_wards (
  region_code VARCHAR(10) NOT NULL,
  district_code VARCHAR(10) NOT NULL,
  code VARCHAR(20) NOT NULL,
  name VARCHAR(120) NOT NULL,
  PRIMARY KEY (region_code, district_code, code),
  KEY idx_locations_ward_name (name),
  CONSTRAINT fk_locations_ward_district FOREIGN KEY (region_code, district_code) REFERENCES locations_districts(region_code, code) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS user_documents (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  user_id INT UNSIGNED NOT NULL,
  document_type ENUM('passport_photo','nida','brela','tin','professional_license','other') NOT NULL,
  original_name VARCHAR(255) NOT NULL,
  stored_name VARCHAR(128) NOT NULL,
  mime VARCHAR(127) NULL,
  size_bytes INT UNSIGNED NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uniq_user_documents_stored (stored_name),
  KEY idx_user_documents_user (user_id),
  CONSTRAINT fk_user_documents_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

ALTER TABLE listings
  ADD COLUMN listing_type ENUM('plot_for_sale','house_for_sale','house_for_rent','apartment') NOT NULL DEFAULT 'plot_for_sale',
  ADD COLUMN furnishing_status ENUM('not_applicable','furnished','unfurnished') NOT NULL DEFAULT 'not_applicable',
  ADD COLUMN region_code VARCHAR(10) NULL,
  ADD COLUMN district_code VARCHAR(10) NULL,
  ADD COLUMN ward_code VARCHAR(20) NULL,
  ADD COLUMN price_min_tzs BIGINT UNSIGNED NULL,
  ADD COLUMN price_max_tzs BIGINT UNSIGNED NULL,
  ADD COLUMN is_taken TINYINT(1) NOT NULL DEFAULT 0,
  ADD COLUMN taken_at TIMESTAMP NULL,
  ADD KEY idx_listings_type_status (listing_type, verification_status, is_taken),
  ADD KEY idx_listings_location (region_code, district_code, ward_code);

UPDATE listings SET price_min_tzs = price_tzs, price_max_tzs = price_tzs WHERE price_tzs IS NOT NULL AND price_min_tzs IS NULL;

ALTER TABLE enquiries
  ADD COLUMN status ENUM('new','contacted','closed') NOT NULL DEFAULT 'new',
  ADD COLUMN admin_notes TEXT NULL,
  ADD KEY idx_enquiries_status (status, created_at);

CREATE TABLE IF NOT EXISTS conversations (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  buyer_user_id INT UNSIGNED NOT NULL,
  status ENUM('open','closed') NOT NULL DEFAULT 'open',
  last_message_at TIMESTAMP NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uniq_conversations_buyer (buyer_user_id),
  KEY idx_conversations_activity (status, last_message_at),
  CONSTRAINT fk_conversations_buyer FOREIGN KEY (buyer_user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS messages (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  conversation_id INT UNSIGNED NOT NULL,
  sender_user_id INT UNSIGNED NOT NULL,
  body TEXT NOT NULL,
  read_at TIMESTAMP NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_messages_conversation (conversation_id, created_at),
  CONSTRAINT fk_messages_conversation FOREIGN KEY (conversation_id) REFERENCES conversations(id) ON DELETE CASCADE,
  CONSTRAINT fk_messages_sender FOREIGN KEY (sender_user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS expert_requests (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  buyer_user_id INT UNSIGNED NOT NULL,
  expert_type ENUM('surveyor','valuer','town_planner','advocate') NOT NULL,
  region_code VARCHAR(10) NOT NULL,
  district_code VARCHAR(10) NOT NULL,
  ward_code VARCHAR(20) NOT NULL,
  description TEXT NOT NULL,
  status ENUM('pending','assigned','closed','cancelled') NOT NULL DEFAULT 'pending',
  assigned_expert_user_id INT UNSIGNED NULL,
  admin_notes TEXT NULL,
  assigned_at TIMESTAMP NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_expert_requests_status (status, expert_type, region_code),
  KEY idx_expert_requests_buyer (buyer_user_id),
  KEY idx_expert_requests_assigned (assigned_expert_user_id),
  CONSTRAINT fk_expert_requests_buyer FOREIGN KEY (buyer_user_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT fk_expert_requests_expert FOREIGN KEY (assigned_expert_user_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

